def detect_lang():
    """语言检测:?lang= > cookie > Accept-Language > zh"""
    lang = request.args.get('lang', '')
    if lang in LANGS:
        return lang
    lang = request.cookies.get(COOKIE_NAME, '')
    if lang in LANGS:
        return lang
    # Accept-Language(zh-CN/zh-TW/zh-HK 都归 zh)
    al = request.accept_languages
    if al:
        best = al.best_match(LANGS)
        if best:
            return best
    return 'zh'


def tr(key, **kw):
    """按 g.lang 取文案;缺 key 时回退中文;支持 {n} 占位"""
    lang = getattr(g, 'lang', 'zh')
    s = STRINGS.get(lang, {}).get(key) or STRINGS['zh'].get(key, key)
    if kw:
        try:
            s = s.format(**kw)
        except Exception:
            pass
    return s
